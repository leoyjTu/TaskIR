import argparse
import gc
import random
from pathlib import Path

import numpy as np
import torch

from utils.downstream_utils import build_downstream_models
from utils.eval_restored_utils import (
    MANIFEST_FIELDS,
    SUMMARY_FIELDS,
    TaskIRResultDataset,
    evaluate_task,
    write_csv,
    write_task_rows,
)


TASKS = ("cls", "seg", "det")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Strictly evaluate restored images generated by TaskIR test.py.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--method_name",
        default="",
        help=(
            "Method name recorded in evaluation CSV files. When results_root "
            "contains method subdirectories, this also selects the subdirectory; "
            "a single method subdirectory is detected automatically."
        ),
    )
    parser.add_argument(
        "--results_root",
        default="test_results",
        help=(
            "Root containing either <task>/restored/<degradation> or "
            "<method>/<task>/restored/<degradation> TaskIR results from test.py."
        ),
    )
    parser.add_argument("--cls_list", default="data_dir/lists/val_cls.jsonl", help="ImageNet-1K evaluation JSONL.")
    parser.add_argument("--seg_list", default="data_dir/lists/val_seg.jsonl", help="Cityscapes evaluation JSONL.")
    parser.add_argument("--det_list", default="data_dir/lists/val_det.jsonl", help="VOC2012 evaluation JSONL.")
    parser.add_argument("--task", choices=("all", *TASKS), default="all", help="Task to evaluate; 'all' requires all three tasks.")
    parser.add_argument("--dataset_root", default="", help="Base path used only for relative JSONL paths.")
    parser.add_argument("--output_root", default="evaluation_results", help="Root for summaries, per-image CSV files and visualizations.")
    parser.add_argument("--check_mapping_only", action="store_true", help="Validate every expected TaskIR result without loading downstream models.")
    parser.add_argument("--save_visualizations", action="store_true", help="Save Grad-CAM, segmentation and detection visualizations.")
    parser.add_argument("--cuda", type=int, default=0, help="Preferred CUDA device; CUDA OOM automatically falls back to CPU.")
    parser.add_argument("--num_workers", type=int, default=0, help="DataLoader worker count.")

    parser.add_argument("--cls_ckpt", default="downstream/ResNet50/ckpt/resnet50-11ad3fa6.pth", help="Frozen ImageNet-1K ResNet-50 checkpoint.")
    parser.add_argument("--seg_ckpt", default="downstream/SegFormer/ckpt/segformer-b5-finetuned-cityscapes-1024-1024", help="Frozen Cityscapes SegFormer-B5 directory.")
    parser.add_argument("--det_ckpt", default="downstream/YOLOv8/ckpt/yolov8n-voc2012.pt", help="Frozen 20-class VOC2012 YOLOv8 checkpoint.")
    parser.add_argument("--det_imgsz", type=int, default=640, help="YOLOv8 evaluation input size.")
    parser.add_argument("--det_conf", type=float, default=0.001, help="YOLOv8 confidence threshold used for mAP predictions.")
    parser.add_argument("--det_iou", type=float, default=0.7, help="YOLOv8 NMS IoU threshold.")
    parser.add_argument("--det_vis_conf", type=float, default=0.25, help="Confidence threshold used only for detection visualizations.")
    parser.add_argument("--det_vis_max_boxes", type=int, default=10, help="Maximum boxes drawn per visualization; zero keeps all.")
    parser.add_argument("--seed", type=int, default=0, help="Random seed.")
    args = parser.parse_args()

    args.cls_num_classes = 1000
    args.seg_num_classes = 19
    args.det_num_classes = 20
    args.ignore_index = 255
    args.max_det_boxes = 100
    return args


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def enabled_tasks(args):
    return TASKS if args.task == "all" else (args.task,)


def preferred_device(cuda_index):
    if not torch.cuda.is_available():
        return torch.device("cpu")
    device = torch.device(f"cuda:{cuda_index}")
    torch.cuda.set_device(device)
    return device


def _is_cuda_oom(error, device):
    return device.type == "cuda" and "out of memory" in str(error).lower()


def clear_cuda_cache():
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def build_task_model(args, task, device):
    downstream = build_downstream_models(args, (task,), device="cpu")
    model = downstream[task].float().eval().requires_grad_(False)
    if device.type != "cuda":
        return model, device
    try:
        model.to(device)
        return model, device
    except RuntimeError as error:
        if not _is_cuda_oom(error, device):
            raise
        print(f"CUDA OOM while loading the {task} evaluation model; switching to CPU.")
        model.to("cpu")
        clear_cuda_cache()
        return model, torch.device("cpu")


def _contains_task_results(results_root, tasks):
    return all((results_root / task / "restored").is_dir() for task in tasks)


def resolve_method_results_root(args, tasks):
    results_root = Path(args.results_root).expanduser().resolve()
    if _contains_task_results(results_root, tasks):
        if not args.method_name:
            args.method_name = "TaskIR"
        return results_root

    if args.method_name:
        method_root = results_root / args.method_name
        if _contains_task_results(method_root, tasks):
            return method_root
        expected = ", ".join(
            str(method_root / task / "restored") for task in tasks
        )
        raise FileNotFoundError(
            f"TaskIR restored directories were not found for method "
            f"{args.method_name!r}. Expected: {expected}. You may also point "
            "--results_root directly to the method directory."
        )

    candidates = sorted(
        child for child in results_root.iterdir()
        if child.is_dir() and _contains_task_results(child, tasks)
    )
    if len(candidates) == 1:
        method_root = candidates[0]
        args.method_name = method_root.name
        print(
            f"Auto-detected method {args.method_name!r} under results root: "
            f"{method_root}"
        )
        return method_root
    if len(candidates) > 1:
        names = ", ".join(candidate.name for candidate in candidates)
        raise RuntimeError(
            f"Multiple method result directories were found under {results_root}: "
            f"{names}. Select one with --method_name."
        )

    expected = ", ".join(
        str(results_root / task / "restored") for task in tasks
    )
    raise FileNotFoundError(
        "TaskIR restored directories were not found. Expected either the direct "
        f"layout ({expected}) or one method subdirectory containing that layout."
    )


def resolve_task_restored_root(method_results_root, task):
    return method_results_root / task / "restored"


def build_datasets(args, tasks, method_results_root):
    datasets = {}
    manifest = []
    for task in tasks:
        restored_root = resolve_task_restored_root(method_results_root, task)
        print(f"[{task}] Restored root: {restored_root}")
        dataset = TaskIRResultDataset(
            list_file=getattr(args, f"{task}_list"),
            task=task,
            restored_root=restored_root,
            dataset_root=args.dataset_root,
            ignore_index=args.ignore_index,
            max_det_boxes=args.max_det_boxes,
        )
        datasets[task] = dataset
        manifest.extend(dataset.manifest_rows())
    return datasets, manifest


def main():
    args = parse_args()
    seed_everything(args.seed)
    tasks = enabled_tasks(args)
    method_results_root = resolve_method_results_root(args, tasks)

    method_output = Path(args.output_root) / args.method_name
    method_output.mkdir(parents=True, exist_ok=True)
    args.visualization_root = str(method_output / "visualizations")
    datasets, manifest = build_datasets(args, tasks, method_results_root)
    manifest_path = method_output / "resolved_manifest.csv"
    write_csv(manifest_path, MANIFEST_FIELDS, manifest)
    print(f"Strict TaskIR mapping verified for {len(manifest)} restored images.")
    print(f"Manifest: {manifest_path}")
    if args.check_mapping_only:
        return

    device = preferred_device(args.cuda)
    summary_rows = []
    print(f"Evaluation device: {device}; FP32 with automatic CUDA OOM CPU fallback.")
    for task in tasks:
        model, device = build_task_model(args, task, device)
        summaries, output_rows, device = evaluate_task(
            args, task, datasets[task], model, device,
        )
        summary_rows.extend(summaries)
        write_task_rows(method_output, task, output_rows)
        del model, datasets[task]
        clear_cuda_cache()

    summary_path = method_output / "summary.csv"
    write_csv(summary_path, SUMMARY_FIELDS, summary_rows)
    print(f"Summary: {summary_path}")


if __name__ == "__main__":
    main()
